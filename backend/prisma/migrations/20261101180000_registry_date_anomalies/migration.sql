-- Записи государственного реестра хранятся так, как их публикует источник.
--
-- В реестре встречаются записи, где срок действия регистрационного
-- удостоверения истекает раньше даты регистрации: например, «ФС
-- 01012002/2879-06» — регистрация 07.02.2006, окончание 07.02.2000. Судя по
-- всему, это опечатки в годе на стороне источника. Таких записей около трёх
-- на тысячу, то есть порядка двухсот на весь реестр.
--
-- Прежний CHECK отвергал их, и настоящие записи реестра просто терялись.
-- Молча «чинить» даты нельзя: зеркало государственного реестра обязано
-- показывать то, что в нём опубликовано.
--
-- Поэтому правило сохраняется для записей, которые заводим мы сами, и
-- снимается для загруженных из реестра (у них заполнен external_registry_id).
-- Каждая такая аномалия попадает в sync_run_errors с кодом
-- REGISTRY_DATE_ANOMALY, то есть остаётся видимой в журнале загрузок.

ALTER TABLE "products"
  DROP CONSTRAINT "products_registration_period_check";

ALTER TABLE "products"
  ADD CONSTRAINT "products_registration_period_check"
  CHECK (
    "external_registry_id" IS NOT NULL
    OR "registration_date" IS NULL
    OR "registration_expires_at" IS NULL
    OR "registration_expires_at" >= "registration_date"
  );
